import os
import smtplib
from email.message import EmailMessage
from datetime import datetime
from dotenv import load_dotenv

load_dotenv()

EMAIL_SENDER = os.getenv("EMAIL_SENDER")
EMAIL_PASSWORD = os.getenv("EMAIL_PASSWORD")

# People who ALWAYS receive VisionGuard alerts
ALERT_RECIPIENTS = [
    email.strip()
    for email in os.getenv("ALERT_RECIPIENTS", "").split(",")
    if email.strip()
]


def send_alert_email(image_path=None, location="Restricted Area"):

    current_time = datetime.now()

    date = current_time.strftime("%d %B %Y")
    time = current_time.strftime("%I:%M:%S %p")

    message = EmailMessage()

    message["Subject"] = "🚨 VisionGuard Alert - Person Detected"
    message["From"] = EMAIL_SENDER
    message["To"] = ", ".join(ALERT_RECIPIENTS)

    message.set_content(
        f"""
VISIONGUARD SECURITY ALERT

⚠️ Person detected in a restricted area.

Detection Details
-----------------
Date: {date}
Time: {time}
Location: {location}
Alert Type: Unauthorized Person Detected

Please take the necessary security action.

This is an automated alert generated by VisionGuard AI.
"""
    )

    # Attach the detected image
    if image_path and os.path.exists(image_path):

        with open(image_path, "rb") as file:
            image_data = file.read()

        message.add_attachment(
            image_data,
            maintype="image",
            subtype="jpeg",
            filename=os.path.basename(image_path)
        )

    try:

        with smtplib.SMTP_SSL("smtp.gmail.com", 465) as smtp:

            smtp.login(
                EMAIL_SENDER,
                EMAIL_PASSWORD
            )

            smtp.send_message(message)

        print("Alert email sent successfully.")
        return True

    except Exception as e:

        print(f"Failed to send alert email: {e}")
        return False


# ============================================================
# SETTINGS
# ============================================================

VIDEO_PATH = "test_data/videos/Restricted_area.mp4"

VIOLATION_FOLDER = "output/violations"

MIN_CONTOUR_AREA = 2500

# Person's feet must remain inside the restricted
# area for this many consecutive frames.
ENTRY_CONFIRM_FRAMES = 5

# Frames outside the area before the system can
# detect another violation.
REARM_FRAMES = 30


# ============================================================
# CREATE OUTPUT FOLDER
# ============================================================

os.makedirs(VIOLATION_FOLDER, exist_ok=True)


# ============================================================
# OPEN VIDEO
# ============================================================

video = cv2.VideoCapture(VIDEO_PATH)

if not video.isOpened():

    print("ERROR: Could not open video.")

    exit()


# ============================================================
# VIDEO INFORMATION
# ============================================================

width = int(video.get(cv2.CAP_PROP_FRAME_WIDTH))
height = int(video.get(cv2.CAP_PROP_FRAME_HEIGHT))
fps = video.get(cv2.CAP_PROP_FPS)

print()
print("============================================")
print("       RESTRICTED AREA ALERT SYSTEM")
print("============================================")
print("Video resolution:", width, "x", height)
print("FPS:", round(fps, 2))
print()


# ============================================================
# RESTRICTED FLOOR AREA
# ============================================================
#
# The coordinates below were mapped from the uploaded
# portrait video.
#
# Reference resolution = 464 x 832
#
# The polygon represents the WHITE FLOOR/PASSAGE.
# It excludes the wall, door and carpet.
# ============================================================

REFERENCE_WIDTH = 464
REFERENCE_HEIGHT = 832

reference_polygon = np.array(
    [
        [175, 558],
        [307, 558],
        [327, 696],
        [104, 696]
    ],
    dtype=np.float32
)


# Scale coordinates if the actual video resolution
# is different from the reference resolution.

scale_x = width / REFERENCE_WIDTH
scale_y = height / REFERENCE_HEIGHT

restricted_area = (
    reference_polygon *
    np.array([scale_x, scale_y])
).astype(np.int32)


# ============================================================
# BACKGROUND SUBTRACTION
# ============================================================

background_subtractor = cv2.createBackgroundSubtractorMOG2(
    history=500,
    varThreshold=45,
    detectShadows=False
)


# ============================================================
# NOISE REMOVAL KERNEL
# ============================================================

kernel = np.ones(
    (5, 5),
    np.uint8
)


# ============================================================
# DETECTION STATE
# ============================================================

inside_frames = 0

outside_frames = 0

violation_saved = False

frame_number = 0


# ============================================================
# MAIN VIDEO LOOP
# ============================================================

while True:

    success, frame = video.read()

    if not success:

        break

    frame_number += 1


    # ========================================================
    # CREATE MOTION MASK
    # ========================================================

    motion_mask = background_subtractor.apply(frame)


    # ========================================================
    # REMOVE SMALL NOISE
    # ========================================================

    motion_mask = cv2.morphologyEx(
        motion_mask,
        cv2.MORPH_OPEN,
        kernel
    )

    motion_mask = cv2.morphologyEx(
        motion_mask,
        cv2.MORPH_CLOSE,
        kernel
    )


    # ========================================================
    # FIND MOVING OBJECTS
    # ========================================================

    contours, _ = cv2.findContours(
        motion_mask,
        cv2.RETR_EXTERNAL,
        cv2.CHAIN_APPROX_SIMPLE
    )


    # ========================================================
    # DRAW RESTRICTED FLOOR
    # ========================================================

    cv2.polylines(
        frame,
        [restricted_area],
        True,
        (0, 0, 255),
        3
    )


    # ========================================================
    # RESTRICTED AREA LABEL
    # ========================================================

    label_x = int(restricted_area[0][0])

    label_y = int(restricted_area[0][1]) - 15

    if label_y < 30:

        label_y = 30


    cv2.putText(
        frame,
        "RESTRICTED FLOOR",
        (label_x, label_y),
        cv2.FONT_HERSHEY_SIMPLEX,
        0.7,
        (0, 0, 255),
        2
    )


    # ========================================================
    # FIND LARGEST RELEVANT MOVING OBJECT
    # ========================================================

    best_box = None

    best_area = 0


    for contour in contours:

        area = cv2.contourArea(contour)


        # Ignore tiny movements.

        if area < MIN_CONTOUR_AREA:

            continue


        x, y, w, h = cv2.boundingRect(contour)


        # Ignore objects that are too small.

        if w < 30 or h < 60:

            continue


        # Keep the largest moving object.

        if area > best_area:

            best_area = area

            best_box = (
                x,
                y,
                w,
                h
            )


    # ========================================================
    # PROCESS MOVING OBJECT
    # ========================================================

    if best_box is not None:

        x, y, w, h = best_box


        # ----------------------------------------------------
        # ESTIMATE FEET POSITION
        # ----------------------------------------------------

        foot_x = x + (w // 2)

        foot_y = y + int(h * 0.97)


        # ----------------------------------------------------
        # CHECK FEET AGAINST RESTRICTED FLOOR
        # ----------------------------------------------------

        position = cv2.pointPolygonTest(
            restricted_area,
            (foot_x, foot_y),
            False
        )


        # ====================================================
        # OUTSIDE RESTRICTED AREA
        # ====================================================

        if position < 0:

            inside_frames = 0

            outside_frames += 1


            # Green bounding box.

            cv2.rectangle(
                frame,
                (x, y),
                (x + w, y + h),
                (0, 255, 0),
                2
            )


            # Green feet point.

            cv2.circle(
                frame,
                (foot_x, foot_y),
                6,
                (0, 255, 0),
                -1
            )


        # ====================================================
        # INSIDE RESTRICTED AREA
        # ====================================================

        else:

            inside_frames += 1

            outside_frames = 0


            # Red bounding box.

            cv2.rectangle(
                frame,
                (x, y),
                (x + w, y + h),
                (0, 0, 255),
                3
            )


            # Red feet point.

            cv2.circle(
                frame,
                (foot_x, foot_y),
                7,
                (0, 0, 255),
                -1
            )


            # Warning.

            cv2.putText(
                frame,
                "PERSON IN RESTRICTED AREA",
                (20, 50),
                cv2.FONT_HERSHEY_SIMPLEX,
                0.75,
                (0, 0, 255),
                3
            )


            # Confirmation counter.

            cv2.putText(
                frame,
                f"Confirming: {inside_frames}/{ENTRY_CONFIRM_FRAMES}",
                (20, 85),
                cv2.FONT_HERSHEY_SIMPLEX,
                0.65,
                (0, 0, 255),
                2
            )


            # =================================================
            # CONFIRM VIOLATION
            # =================================================

            if (
                inside_frames >= ENTRY_CONFIRM_FRAMES
                and not violation_saved
            ):

                timestamp = datetime.now().strftime(
                    "%Y%m%d_%H%M%S"
                )


                filename = (
                    "violation_"
                    + timestamp
                    + "_frame_"
                    + str(frame_number)
                    + ".jpg"
                )


                screenshot_path = os.path.join(
                    VIOLATION_FOLDER,
                    filename
                )


                # SAVE ONE PICTURE ONLY.

                cv2.imwrite(
                    screenshot_path,
                    frame
                )

                # Send email alert with the violation image
                send_alert_email(
                    image_path=screenshot_path,
                    location="Restricted Area"
                )

                violation_saved = True


                print()
                print("============================================")
                print("          VIOLATION CONFIRMED")
                print("============================================")
                print(
                    "Frame:",
                    frame_number
                )
                print(
                    "Video time:",
                    round(frame_number / fps, 2),
                    "seconds"
                )
                print(
                    "Picture saved:",
                    screenshot_path
                )
                print()


    # ========================================================
    # NO MOVING OBJECT
    # ========================================================

    else:

        inside_frames = 0

        outside_frames += 1


    # ========================================================
    # RE-ARM SYSTEM
    # ========================================================

    if outside_frames >= REARM_FRAMES:

        violation_saved = False


    # ========================================================
    # SYSTEM STATUS
    # ========================================================

    if violation_saved:

        status_text = "ALERT - VIOLATION CAPTURED"

        status_color = (0, 0, 255)

    elif inside_frames > 0:

        status_text = "VERIFYING ENTRY"

        status_color = (0, 165, 255)

    else:

        status_text = "MONITORING"

        status_color = (0, 255, 0)


    cv2.putText(
        frame,
        status_text,
        (20, height - 25),
        cv2.FONT_HERSHEY_SIMPLEX,
        0.7,
        status_color,
        2
    )


    # ========================================================
    # DISPLAY
    # ========================================================

    cv2.imshow(
        "Restricted Area Alert System",
        frame
    )


    # ========================================================
    # PRESS Q TO EXIT
    # ========================================================

    if cv2.waitKey(1) & 0xFF == ord("q"):

        break


# ============================================================
# CLEANUP
# ============================================================

video.release()

cv2.destroyAllWindows()


print()
print("============================================")
print("          PROCESSING COMPLETED")
print("============================================")
print("Violation pictures are stored in:")
print(VIOLATION_FOLDER)
print()