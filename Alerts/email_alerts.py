import os
import smtplib
from email.message import EmailMessage
from datetime import datetime
from dotenv import load_dotenv

load_dotenv()

EMAIL_SENDER = os.getenv("EMAIL_SENDER")
EMAIL_PASSWORD = os.getenv("EMAIL_PASSWORD")

# People who ALWAYS receive VisionGuard alerts
ALERT_RECIPIENTS = [
    email.strip()
    for email in os.getenv("ALERT_RECIPIENTS", "").split(",")
    if email.strip()
]


def send_alert_email(image_path=None, location="Restricted Area"):

    current_time = datetime.now()

    date = current_time.strftime("%d %B %Y")
    time = current_time.strftime("%I:%M:%S %p")

    message = EmailMessage()

    message["Subject"] = "🚨 VisionGuard Alert - Person Detected"
    message["From"] = EMAIL_SENDER
    message["To"] = ", ".join(ALERT_RECIPIENTS)

    message.set_content(
        f"""
VISIONGUARD SECURITY ALERT

⚠️ Person detected in a restricted area.

Detection Details
-----------------
Date: {date}
Time: {time}
Location: {location}
Alert Type: Unauthorized Person Detected

Please take the necessary security action.

This is an automated alert generated by VisionGuard AI.
"""
    )

    # Attach the detected image
    if image_path and os.path.exists(image_path):

        with open(image_path, "rb") as file:
            image_data = file.read()

        message.add_attachment(
            image_data,
            maintype="image",
            subtype="jpeg",
            filename=os.path.basename(image_path)
        )

    try:

        with smtplib.SMTP_SSL("smtp.gmail.com", 465) as smtp:

            smtp.login(
                EMAIL_SENDER,
                EMAIL_PASSWORD
            )

            smtp.send_message(message)

        print("Alert email sent successfully.")
        return True

    except Exception as e:

        print(f"Failed to send alert email: {e}")
        return False